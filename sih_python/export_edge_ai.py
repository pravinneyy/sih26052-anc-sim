    if os.path.exists(args.checkpoint):
        model.load_state_dict(torch.load(args.checkpoint, map_location='cpu'))
        print(f"[export] Loaded checkpoint: {args.checkpoint}")
    else:
        print(f"[export] No checkpoint found at '{args.checkpoint}' — using hand-tuned weights")

    model.eval()

    # Export
    export_c_header  (model, os.path.join(args.out_dir, "arm_nn_weights.h"))
    export_js_weights(model, os.path.join(args.out_dir, "aiml_weights.js"))
    export_onnx      (model, os.path.join(args.out_dir, "model.onnx"))
    check_quantisation_accuracy(model)

    print("\n[export] All exports complete.")
    print(f"  C header   -> {args.out_dir}/arm_nn_weights.h  (include in Cortex-M7 project)")
    print(f"  JS weights  -> {args.out_dir}/aiml_weights.js   (load before aiml_engine.js)")
    print(f"  ONNX model  -> {args.out_dir}/model.onnx        (deployment pipeline)")
